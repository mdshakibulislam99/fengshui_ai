    # DeepSeek
    lines.append("# DeepSeek AI Chatbot API")
    lines.append(f"DEEPSEEK_API_KEY={current_config.get('DEEPSEEK_API_KEY', 'YOUR_DEEPSEEK_API_KEY_HERE')}")
    lines.append(f"DEEPSEEK_API_URL={current_config.get('DEEPSEEK_API_URL', 'https://api.deepseek.com/v1/chat/completions')}")
    lines.append(f"DEEPSEEK_MODEL={current_config.get('DEEPSEEK_MODEL', 'deepseek-chat')}\n")
    
    # OpenTopography
    lines.append("# OpenTopography API (optional)")
    lines.append(f"OPENTOPO_API_KEY={current_config.get('OPENTOPO_API_KEY', 'YOUR_OPENTOPO_API_KEY_HERE')}\n")
    
    # Flask
    lines.append("# Flask Configuration")
    lines.append(f"DEBUG={current_config.get('DEBUG', 'False')}")
    lines.append(f"HOST={current_config.get('HOST', '0.0.0.0')}")
    lines.append(f"PORT={current_config.get('PORT', '5000')}\n")
    
    # HydroSHEDS
    lines.append("# HydroSHEDS (Rivers) via Google Earth Engine")
