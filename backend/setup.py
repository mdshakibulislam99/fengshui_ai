def verify_deepseek_key(api_key):
    """Test the DeepSeek API key"""
    print_info("Testing DeepSeek API key...")
    
    try:
        import requests
        
        headers = {
            "Content-Type": "application/json",
            "Authorization": f"Bearer {api_key}"
        }
        
        payload = {
            "model": "deepseek-chat",
            "messages": [{"role": "user", "content": "Test"}],
            "max_tokens": 10,
            "temperature": 0.1
        }
        
        response = requests.post(
            "https://api.deepseek.com/v1/chat/completions",
            headers=headers,
            json=payload,
            timeout=10
        )
        
        if response.status_code == 200:
            print_success("DeepSeek API key is valid!")
            return True
        elif response.status_code == 401:
            print_error("Invalid API key (401 Unauthorized)")
            return False
        else:
            print_warning(f"API returned status {response.status_code}")
            print_info(f"Response: {response.text[:200]}")
            return False
    
    except requests.exceptions.RequestException as e:
        print_warning(f"Connection error: {e}")
        print_info("You can test the key later by running an analysis")
        return True
    except Exception as e:
        print_warning(f"Error testing API: {e}")
        return True

def show_current_config():
    """Display current configuration"""
    print_section("📋 Current Configuration")
    
    current_config = load_current_config()
    
    if not current_config:
        print_warning("No .env file found. Run setup to create one.\n")
        return
    
    # Display important keys
    important_keys = [
        ('DEEPSEEK_API_KEY', 'DeepSeek API Key'),
        ('DEEPSEEK_MODEL', 'DeepSeek Model'),
        ('AMAP_API_KEY', 'AMap API Key'),
    ]
    
    for key, label in important_keys:
        value = current_config.get(key, 'NOT SET')
        if value == 'NOT SET' or value == 'YOUR_DEEPSEEK_API_KEY_HERE':
            print_warning(f"{label}: NOT CONFIGURED")
        else:
            if len(value) > 15:
                display_value = f"{value[:10]}...{value[-5:]}"
            else:
                display_value = f"{'*' * len(value)}"
            print_success(f"{label}: {display_value}")
    
    print()

def main():
    """Main setup flow"""
    print_header("🔮 FengShui AI - Configuration Setup")
    
    print(f"{Colors.CYAN}This will help you configure your API keys.{Colors.ENDC}\n")
    
    if check_env_file():
        print_info(".env file already exists")
        show_current_config()
        
        action = input(f"{Colors.BOLD}What would you like to do? (1=Add/Update Key, 2=View Config, 3=Exit): {Colors.ENDC}").strip()
        
        if action == '2':
            show_current_config()
            return
        elif action != '1':
            print_info("Exiting setup")
            return
    else:
        print_warning(".env file not found. Creating new configuration...\n")
    
    # Setup DeepSeek
    api_key = setup_deepseek()
    
    if api_key:
        # Update .env file
        try:
            update_env_file({
                'DEEPSEEK_API_KEY': api_key,
                'DEEPSEEK_API_URL': 'https://api.deepseek.com/v1/chat/completions',
                'DEEPSEEK_MODEL': 'deepseek-chat'
            })
            print_success(".env file created/updated successfully!")
            
            # Verify the key
            verify_deepseek_key(api_key)
            
            print_section("✅ Setup Complete!")
            print(f"{Colors.GREEN}Your API key is now configured.{Colors.ENDC}")
            print(f"{Colors.BLUE}Next steps:{Colors.ENDC}")
            print("1. Restart your Flask backend server")
            print("2. Reload your frontend in the browser")
            print("3. The chatbot should now be fully functional\n")
            
        except Exception as e:
            print_error(f"Failed to update .env file: {e}\n")
    else:
        print_error("Setup cancelled. No changes made.\n")

if __name__ == '__main__':
    try:
        main()
    except KeyboardInterrupt:
        print(f"\n{Colors.YELLOW}Setup cancelled by user{Colors.ENDC}\n")
        sys.exit(0)
    except Exception as e:
        print_error(f"Setup error: {e}\n")
        sys.exit(1)
