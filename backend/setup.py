#!/usr/bin/env python3
"""
FengShui AI - Configuration Setup Script
Helps users configure their API keys easily
"""

import os
import sys
from pathlib import Path
from dotenv import load_dotenv, dotenv_values

# Colors for terminal output
class Colors:
    HEADER = '\033[95m'
    CYAN = '\033[96m'
    BLUE = '\033[94m'
    GREEN = '\033[92m'
    YELLOW = '\033[93m'
    RED = '\033[91m'
    ENDC = '\033[0m'
    BOLD = '\033[1m'
    UNDERLINE = '\033[4m'

def print_header(text):
    print(f"\n{Colors.HEADER}{Colors.BOLD}{'='*60}{Colors.ENDC}")
    print(f"{Colors.HEADER}{Colors.BOLD}{text:^60}{Colors.ENDC}")
    print(f"{Colors.HEADER}{Colors.BOLD}{'='*60}{Colors.ENDC}\n")

def print_section(text):
    print(f"{Colors.CYAN}{Colors.BOLD}{text}{Colors.ENDC}")
    print(f"{Colors.CYAN}{'-'*len(text)}{Colors.ENDC}")

def print_success(text):
    print(f"{Colors.GREEN}✓ {text}{Colors.ENDC}")

def print_error(text):
    print(f"{Colors.RED}✗ {text}{Colors.ENDC}")

def print_warning(text):
    print(f"{Colors.YELLOW}⚠ {text}{Colors.ENDC}")

def print_info(text):
    print(f"{Colors.BLUE}ℹ {text}{Colors.ENDC}")

def check_env_file():
    """Check if .env file exists"""
    return os.path.exists('.env')

def load_current_config():
    """Load current configuration from .env"""
    if check_env_file():
        return dotenv_values('.env')
    return {}

def get_env_value(key, current_config):
    """Get current value of env variable"""
    return current_config.get(key, 'NOT SET')

def setup_deepseek():
    """Set up DeepSeek API key"""
    print_section("🤖 DeepSeek AI Chatbot Setup")
    
    print_info("DeepSeek provides affordable AI API access")
    print_info("Free tier: Usually $5-10 in free credits")
    print_info("Paid tier: ~$0.14 per million input tokens\n")
    
    print("Steps to get your API key:")
    print("1. Go to: https://platform.deepseek.com/api_keys")
    print("2. Sign up or log in")
    print("3. Create a new API key")
    print("4. Copy the key\n")
    
    api_key = input(f"{Colors.BOLD}Enter your DeepSeek API key: {Colors.ENDC}").strip()
    
    if not api_key or api_key == "YOUR_DEEPSEEK_API_KEY_HERE":
        print_error("Invalid API key")
        return False
    
    if len(api_key) < 20:
        print_warning("API key seems too short. Are you sure?")
        confirm = input(f"{Colors.BOLD}Continue anyway? (y/n): {Colors.ENDC}").lower()
        if confirm != 'y':
            return False
    
    print_success(f"DeepSeek API key configured: {api_key[:10]}...{api_key[-5:]}")
    return api_key

def update_env_file(config_dict):
    """Update or create .env file with new config"""
    current_config = load_current_config()
    current_config.update(config_dict)
    
    # Build .env content
    lines = []
    lines.append("# FengShui AI Configuration")
    lines.append("# Generated by setup script\n")
    
    # AMap
    lines.append("# AMap API Configuration")
