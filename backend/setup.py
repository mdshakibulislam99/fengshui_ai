    lines.append(f"HYDROSHEDS_GEE_SERVICE_ACCOUNT_PATH={current_config.get('HYDROSHEDS_GEE_SERVICE_ACCOUNT_PATH', 'backend/dem/service_account.json')}")
    lines.append(f"HYDROSHEDS_FLOW_ACC_DATASET={current_config.get('HYDROSHEDS_FLOW_ACC_DATASET', 'WWF/HydroSHEDS/15ACC')}")
    lines.append(f"HYDROSHEDS_FLOW_ACC_THRESHOLD={current_config.get('HYDROSHEDS_FLOW_ACC_THRESHOLD', '1')}")
    lines.append(f"HYDROSHEDS_PIXEL_SIZE_M={current_config.get('HYDROSHEDS_PIXEL_SIZE_M', '500')}")
    lines.append(f"HYDROSHEDS_RADIUS_M={current_config.get('HYDROSHEDS_RADIUS_M', '1000')}")
    
